export function primeMinister(y: number, m: number): string {
  const t = y * 12 + m;
  if (t < 2004 * 12 + 3) return "Михаил Касьянов";
  if (t < 2007 * 12 + 9) return "Михаил Фрадков";
  if (t < 2008 * 12 + 5) return "Виктор Зубков";
  if (t < 2012 * 12 + 5) return "Владимир Путин";
  if (t < 2020 * 12 + 1) return "Дмитрий Медведев";
  return "Михаил Мишустин";
}

